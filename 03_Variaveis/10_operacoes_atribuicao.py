# PY03 - Operações de atribuição
num1 = 10
print(f"Valor de num1: {num1}")
num1 += 5  # num1 = num1 + 5
print(f"Após somar 5: {num1}")
num1 -= 3  # num1 = num1 - 3
print(f"Após subtrair 3: {num1}")
num1 *= 7  # num1 = num1 * 7
print(f"Após multiplicar por 7: {num1}")
num1 /= 2  # num1 = num1 / 2
print(f"Após dividir por 2: {num1}")